from math import dist


# --- ЗАДАНИЕ №14: Системы счисления ---
"""
    Аргументы:
    value (int): Десятичное число, которое нужно преобразовать.
    osn (int): Основание целевой системы счисления (например, 2, 8, 16). """

def value_dec_to_any(value, osn):
    s = ''
    if value == 0: return '0'  # Обработка случая, если на вход пришел нол
    while value > 0:
        s = str(value % osn) + s  # Добавляем остаток (цифру новой системы) в строку
        value //= osn  # ИСПРАВЛЕНО: Было просто //, теперь //= (уменьшаем число)
    return s


# --- ЗАДАНИЕ №15 / №25: Делители и простые числа ---
"""
    Аргументы:
    x (int): Число, которое мы проверяем на "простоту" (имеет ли оно делители кроме 1 и себя).
    """


def prime(x):
    for i in range(2, int(x ** 0.5) + 1):
        if x % i == 0:  # Если x делится на i без остатка — число не простое
            return False
    return x != 1  # Возвращаем True, если x больше 1 и делителей не найдено


# --- ЗАДАНИЕ №27: Кластеризация (Алгоритм DBSCAN) ---
"""
    Аргументы:
    a (list): Список всех точек. Каждая точка — это список или кортеж с координатами [x, y, ...].
    r (float/int): Радиус "соседства". Максимальное расстояние, при котором точки считаются одной группой.

    Логика:
    cl (list): Список кластеров. Каждый элемент внутри — это отдельный кластер (список точек).
    i (list/tuple): Точка, которая уже находится в текущем кластере и "ищет" себе соседей.
    j (list/tuple): Точка из общего списка 'a', которую мы проверяем на близость к точке 'i'.
    """

def dbscan(a, r):
    cl = []
    while a:
        # Извлекаем первую точку из 'a' и создаем новый кластер
        cl.append([a.pop(0)])

        # Перебираем точки в только что созданном кластере (cl[-1])
        for i in cl[-1]:
            # Проверяем все оставшиеся точки в 'a'
            for j in a[:]:
                # dist(i[:2], j[:2]) берет первые две координаты (x и y) и считает расстояние
                if dist(i[:2], j[:2]) < r:
                    cl[-1].append(j)  # Добавляем точку j в текущий кластер
                    a.remove(j)  # Удаляем её из общего списка, чтобы не обрабатывать дважды
    return cl