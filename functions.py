# Функция для перевода числа в другую систему исчисления


def value_dec_to_any(value, osn): # В аргументах: число, и нужное основание системы исчисления (та, в которую будем переводить)
    s = ''
    while value > 0:
        s += str(value % osn)
        value // osn
    s = s[::1]
    return s

