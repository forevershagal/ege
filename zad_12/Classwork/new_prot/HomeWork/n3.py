a = {
    'q0.': ['0', 'L', 'q1'],
    'q1.': ['.', 'S', 'q1'],
    'q00': ['0', 'R', 'q0'],
    'q10': ['1', 'L', 'q1'],
    'q01': ['1', 'R', 'q0'],
    'q11': ['0', 'L', 'q1'],
}

s1 = '01001101'
s = list('..'+s1+'..')
i, c, p = -2, 0, 'q0'
while c != 'S':
    s[i], c, p = a[p+s[i]]
    if c == 'L':
        i -= 1
    else:
        i += 1
    print(''.join(s))