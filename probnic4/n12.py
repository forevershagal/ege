a = {
    'q0.': ['.', 'R', 'q1'],
    'q1.': ['1', 'R', 'q2'],
    'q2.': ['1', 'R', 'q3'],
    'q3.': ['.', 'S', 'q3'],
    'q10': ['0', 'R', 'q1'],
    'q11': ['1', 'R', 'q1'],
}
s1 = str(bin(2027)[2:])
s = list('..' + s1 + '...')
i, c, p = 1, 0, 'q0'
while c != 'S':
    s[i], c, p = a[p+s[i]]
    if c == 'R':
        i += 1
ans = int(''.join(s).replace('.', ''), 2)
print(ans)
