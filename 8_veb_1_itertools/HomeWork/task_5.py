# АНАСТАСИЯ из букв своего имени составляет слова перестановкой исходных букв.
# Сколько различных слов может составить АНАСТАСИЯ,
# если первая буква не может быть согласной?

from itertools import *

a = 'АНАСТАСИЯ'
c = set()

for i in permutations(a):
    s = ''.join(i)

    if (s[0] not in 'НСТ'):
        c.add(s)

print(len(c))

