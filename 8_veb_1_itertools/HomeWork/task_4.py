# Сколько 7  -буквенных слов можно составить
# из букв К, О, М, П, Ь, Ю, Т, Е, Р?
# Буквы Ю и Т должны быть использованы по два раза.
# Остальные буквы можно использовать сколько угодно раз.

from itertools import *

a = 'КОМПЬЮТЕР'
c = 0

for i in product(a, repeat=7):

    s = ''.join(i)

    if (s.count('Ю') == 2) and (s.count('Т') == 2):
        c += 1

print(c)