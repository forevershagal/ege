# Петя составляет слова, состоящие из 6 букв, из символов С, О, Н.
# В каждом слове есть хотя бы две буквы Н и нет сочетания НС.
# Каждая буква может встречаться любое количество раз.
# Сколько слов может составить Петя?



from itertools import *

a = 'СОН'
c = 0

for i in product(a, repeat=6):
    s = ''.join(i)

    if (s.count('Н') >= 2) and (s.count('НС') == 0):
        print(s)
        c += 1

print(c)