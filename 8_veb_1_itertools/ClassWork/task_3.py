# Гоша составлет восьмизначные числа.
# Причем рядом не дожны стоять цифры с одинаковым остатком от деления на 5,
# а также на последнем месте может быть только четная цифра.
# Сколько чисел может составить Гоша?

from itertools import *

a = '0123456789'
c = 0
for i in product(a, repeat=8):
    s = ''.join(i)

    t = [int(s[g]) % 5 != int(s[g + 1]) % 5 for g in range(7)]

    if (s[0] != '0') and all(t) and (int(s[-1]) % 2 == 0):
        c += 1


print(c)