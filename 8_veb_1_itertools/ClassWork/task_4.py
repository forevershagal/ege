# Демид составляет пятибуквенные слова из букв КРОВАТЬ,
# содержащие букву Р, но не более четырех раз.
# Остальные буквы не могут повторяться.
# Сколько различных слов может составить Демид?

from itertools import *

a = 'КРРРРОВАТЬ'
c = set()


for i in permutations(a, 5):

    s = ''.join(i)

    if ('Р' in s):
        print(s)
        c.add(s)

print(len(c))