# ==================ЗАДАЧА=====================
# Гоша составляет восьмизначные числа.
# Причём рядом не должны стоять цифры с одинаковым
# остатком от деления на 5,
# а также на последнем месте может быть только чётная цифра.
# Сколько чисел может составить Гоша?
# =============================================



# ============================================
# ПОДГОТОВКА ДАННЫХ: ГРУППИРУЕМ ЦИФРЫ ПО ОСТАТКАМ
# ============================================

def count_numbers():
    # Сначала создаём словарь, который показывает,
    # какие цифры относятся к каждому остатку от деления на 5
    # Ключ: остаток (0,1,2,3,4)
    # Значение: список цифр с таким остатком
    digits_by_rem = {
        0: [0, 5],  # цифры 0 и 5: 0%5=0, 5%5=0
        1: [1, 6],  # цифры 1 и 6: 1%5=1, 6%5=1
        2: [2, 7],  # цифры 2 и 7: 2%5=2, 7%5=2
        3: [3, 8],  # цифры 3 и 8: 3%5=3, 8%5=3
        4: [4, 9]  # цифры 4 и 9: 4%5=4, 9%5=4
    }

    # ============================================
    # ШАГ 1: Считаем цифры для ПЕРВОЙ позиции
    # Условие: первая цифра не может быть 0
    # ============================================

    # Создаём список из 5 нулей: [0,0,0,0,0]
    # Каждый элемент соответствует остатку от 0 до 4
    # first_counts[0] = сколько цифр с остатком 0 можно поставить на первое место (исключая 0)
    first_counts = [0] * 5

    # Перебираем все остатки от 0 до 4
    for rem in range(5):
        count = 0  # счётчик для этого остатка

        # Перебираем все цифры с данным остатком
        for d in digits_by_rem[rem]:
            # Проверяем: если это не 0, то можно использовать
            if d != 0:  # только для первой цифры исключаем 0
                count += 1

        # Записываем результат для этого остатка
        first_counts[rem] = count

    # После этого цикла first_counts = [1, 2, 2, 2, 2]
    # Потому что:
    # - Для остатка 0: цифры [0,5], но 0 нельзя → только 5 → 1 вариант
    # - Для остатка 1: цифры [1,6], обе можно → 2 варианта
    # - Для остатка 2: цифры [2,7], обе можно → 2 варианта
    # - Для остатка 3: цифры [3,8], обе можно → 2 варианта
    # - Для остатка 4: цифры [4,9], обе можно → 2 варианта

    # ============================================
    # ШАГ 2: Считаем цифры для ПРОМЕЖУТОЧНЫХ позиций (2-7)
    # Здесь можно любую цифру (включая 0), главное чтобы остаток отличался
    # ============================================

    # mid_counts[rem] = сколько всего цифр с остатком rem (для позиций 2-7)
    mid_counts = [len(digits_by_rem[rem]) for rem in range(5)]
    # Результат: [2, 2, 2, 2, 2] (для каждого остатка по 2 цифры)

    # ============================================
    # ШАГ 3: Считаем цифры для ПОСЛЕДНЕЙ    позиции (8-я)
    # Условие: последняя цифра должна быть чётной
    # ============================================

    # last_counts[rem] = сколько ЧЁТНЫХ цифр с остатком rem
    last_counts = [0] * 5  # список из 5 нулей

    for rem in range(5):
        count = 0  # счётчик чётных цифр для этого остатка

        # Перебираем все цифры с данным остатком
        for d in digits_by_rem[rem]:
            # Проверяем чётность: d % 2 == 0
            if d % 2 == 0:  # чётная цифра
                count += 1

        # Записываем результат
        last_counts[rem] = count

    # После этого цикла last_counts = [1, 1, 1, 1, 1]
    # Потому что:
    # - Остаток 0: цифры [0,5] → чётная только 0 → 1 вариант
    # - Остаток 1: цифры [1,6] → чётная только 6 → 1 вариант
    # - Остаток 2: цифры [2,7] → чётная только 2 → 1 вариант
    # - Остаток 3: цифры [3,8] → чётная только 8 → 1 вариант
    # - Остаток 4: цифры [4,9] → чётная только 4 → 1 вариант

    # ============================================
    # ОСНОВНАЯ ЧАСТЬ: ДИНАМИЧЕСКОЕ ПРОГРАММИРОВАНИЕ
    # ============================================

    # Создаём таблицу (список списков) для динамического программирования
    # dp[pos][rem] - сколько способов заполнить первые (pos+1) цифр,
    #                чтобы последняя цифра имела остаток rem

    # Индексы:
    # pos от 0 до 7 (0=1 цифра, 1=2 цифры, ..., 7=8 цифр)
    # rem от 0 до 4 (остаток последней цифры)

    # ШАГ 4.1: Инициализируем первую строку таблицы (pos=0, т.е. 1 цифра)
    # Берём first_counts как есть
    dp = [first_counts[:]]  # создаём список с одной строкой - копией first_counts
    # dp[0] = [1, 2, 2, 2, 2] - это мы уже посчитали выше

    # ============================================
    # ШАГ 4.2: Заполняем таблицу для позиций 2-7 (индексы 1..6)
    # Это цифры на позициях с 2-й по 7-ю
    # ============================================

    # Цикл по позициям от 2 до 7
    # В индексах dp: от 1 до 6 (всего 6 позиций)
    for pos in range(1, 7):
        # Создаём новую строку для текущей позиции (пока все нули)
        new_dp = [0] * 5  # [0,0,0,0,0]

        # Перебираем все возможные остатки ПРЕДЫДУЩЕЙ цифры
        for prev_rem in range(5):
            # Если нет ни одного способа получить предыдущую цифру с остатком prev_rem,
            # то пропускаем - нечего дальше считать
            if dp[pos - 1][prev_rem] == 0:
                continue  # переходим к следующему prev_rem

            # Перебираем все возможные остатки ТЕКУЩЕЙ цифры
            for new_rem in range(5):
                # Условие задачи: остатки соседних цифр должны РАЗЛИЧАТЬСЯ
                if new_rem == prev_rem:
                    continue  # пропускаем, если остатки совпадают

                # Формула динамического программирования:
                # Количество способов получить текущую цифру с остатком new_rem =
                # = (кол-во способов получить предыдущую цифру с остатком prev_rem)
                #   × (кол-во цифр с остатком new_rem)

                # Пример:
                # Если есть 5 способов получить на предыдущей позиции остаток 1,
                # и для нового остатка 0 есть 2 цифры (0 и 5),
                # то мы можем получить 5×2=10 способов для новой позиции

                new_dp[new_rem] += dp[pos - 1][prev_rem] * mid_counts[new_rem]

        # Добавляем новую строку в таблицу dp
        dp.append(new_dp)
        # Теперь dp содержит на одну строку больше

    # После этого цикла таблица dp полностью заполнена для позиций 1-7
    # dp[0] = результаты для 1 цифры
    # dp[1] = результаты для 2 цифр
    # ...
    # dp[6] = результаты для 7 цифр

    # ============================================
    # ШАГ 4.3: Считаем ПОСЛЕДНЮЮ цифру (8-я, позиция 8)
    # Особенность: последняя цифра должна быть ЧЁТНОЙ
    # ============================================

    total = 0  # общий счётчик всех возможных чисел

    # Перебираем все возможные остатки ПРЕДПОСЛЕДНЕЙ цифры (7-я цифра)
    for prev_rem in range(5):
        # Если нет способов получить такую 7-ю цифру, пропускаем
        if dp[6][prev_rem] == 0:
            continue

        # Перебираем все возможные остатки ПОСЛЕДНЕЙ цифры (8-я цифра)
        for last_rem in range(5):
            # Условие: остатки должны отличаться
            if last_rem == prev_rem:
                continue

            # К формуле добавляем:
            # (кол-во способов получить 7 цифр с остатком prev_rem)
            # × (кол-во ЧЁТНЫХ цифр с остатком last_rem)

            total += dp[6][prev_rem] * last_counts[last_rem]

    # ============================================
    # ШАГ 5: Возвращаем результат
    # ============================================
    return total


# ============================================
# ЗАПУСК ПРОГРАММЫ
# ============================================
result = count_numbers()
print(result)